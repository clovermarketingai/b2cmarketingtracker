#!/usr/bin/env node
// Generates docs/METRICS.md from lib/dashboard/catalog.js so the metric
// reference can never drift from what the dashboard computes.
//
//   npm run docs        (= node scripts/gen-metrics-doc.mjs)
//   node scripts/gen-metrics-doc.mjs --check   exits 1 when docs/METRICS.md is out of date
//
// Pure: reads the catalog, writes one Markdown file. No network, no env.

import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  SECTIONS, STATUS, COST_CATEGORIES, DATASET_LABEL, LINE_LABEL, BUSINESS_COST_ROWS, OWNER_COST_ROWS,
} from '../lib/dashboard/catalog.js';
import { DEFAULT_TZ, RANGE_LABEL } from '../lib/dashboard/dates.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'docs', 'METRICS.md');

/* ---------------------------------------------------------------------------
 * Small formatters
 * ------------------------------------------------------------------------ */

/** Escape a cell for a Markdown table (pipes and newlines would break the row). */
export function cell(text) {
  return String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim() || '—';
}

const UNIT_LABEL = {
  currency: 'currency',
  number: 'count',
  percent: 'percent',
  ratio: 'ratio (x)',
  seconds: 'seconds',
  decimal: 'decimal',
};

const DIR_LABEL = {
  higher: 'Higher',
  lower: 'Lower',
  none: 'Context only',
};

/** Render a row's dataset dependencies as their human labels. */
export function needsLabel(needs) {
  if (!needs || !needs.length) return 'nothing (constant)';
  return needs.map(k => DATASET_LABEL[k] || k).join(', ');
}

/** Markdown table for one section. */
export function sectionTable(section) {
  const head = '| Row id | Label | Unit | Better | Accumulates? | Needs | Formula |\n|---|---|---|---|---|---|---|';
  const lines = section.rows.map(r => [
    '`' + r.id + '`',
    r.emphasis === 'primary' ? `**${cell(r.label)}**` : cell(r.label),
    UNIT_LABEL[r.unit] || r.unit,
    DIR_LABEL[r.dir] || r.dir,
    r.cumulative ? 'Yes' : 'No',
    cell(needsLabel(r.needs)),
    cell(r.formula),
  ].join(' | '));
  return head + '\n' + lines.map(l => `| ${l} |`).join('\n');
}

/** The ordered pace bands (those with a numeric `min`), best first. */
export function paceBands(status = STATUS) {
  return Object.entries(status)
    .filter(([, v]) => typeof v.min === 'number')
    .sort((a, b) => b[1].min - a[1].min)
    .map(([key, v]) => ({ key, ...v }));
}

/** Markdown table of the status bands with their exact thresholds. */
export function statusTable(status = STATUS) {
  const bands = paceBands(status);
  const rows = bands.map((b, i) => {
    const upper = i === 0 ? null : bands[i - 1].min;
    const lower = Number.isFinite(b.min) ? b.min : null;
    let range;
    if (lower != null && upper != null) range = `${lower.toFixed(2)} ≤ pace < ${upper.toFixed(2)}`;
    else if (lower != null) range = `pace ≥ ${lower.toFixed(2)}`;
    else range = `pace < ${upper.toFixed(2)}`;
    return `| \`${b.key}\` | ${b.label} | ${b.tone} | ${range} |`;
  });
  const special = Object.entries(status)
    .filter(([, v]) => typeof v.min !== 'number')
    .map(([key, v]) => `| \`${key}\` | ${v.label} | ${v.tone} | ${SPECIAL_STATUS_WHEN[key] || '—'} |`);
  return '| Status | Label | Tone | When |\n|---|---|---|---|\n' + [...rows, ...special].join('\n');
}

const SPECIAL_STATUS_WHEN = {
  set_target: 'no target for this row and month in Dashboard Targets',
  no_data: 'the MTD value is null (a needed source is unavailable, or the ratio cannot be computed)',
  partial: 'the row is context only (`dir` = none): a target is stored but no pace is judged',
};

/* ---------------------------------------------------------------------------
 * Document
 * ------------------------------------------------------------------------ */

export function buildDoc() {
  const out = [];
  const p = (s = '') => out.push(s);

  p('# Command Center metrics');
  p();
  p('<!-- GENERATED by scripts/gen-metrics-doc.mjs from lib/dashboard/catalog.js. Do not edit by hand: run `npm run docs`. -->');
  p();
  p('Every row the Command Center shows, with its exact definition. The formulas are implemented in `lib/dashboard/compute.js`; this file is generated from `lib/dashboard/catalog.js`, which is the single source of truth for what the dashboard shows.');
  p();
  p('**How to read the tables**');
  p();
  p('- **Row id** is the stable identifier. It is the `Metric` value in the Airtable *Dashboard Targets* table, the `ids=` value for `GET /api/v1/daily`, and the `id` in `GET /api/v1/metrics?format=flat`. Some ids appear in more than one section on purpose (for example `replacement_rate` and `hs_billed_value`); they are the same number.');
  p('- **Label** is what the UI prints. Bold rows are the *primary* rows: the ones read first, and the ones the daily snapshot captures.');
  p('- **Unit**: `currency` (dollars, two decimals), `count`, `percent` (0–100, not a fraction), `ratio (x)`, `seconds`, `decimal`.');
  p('- **Better**: whether a higher or a lower number is good. *Context only* rows carry no judgement: their status is `partial` when a monthly target is stored for them and `set_target` otherwise (a target on such a row is optional and only ever yields `partial`).');
  p('- **Accumulates?**: *Yes* for sums that grow through the month (spend, leads, cash), so pace compares against the share of the monthly target that should be reached by today. *No* for rates and averages, which compare straight against the target.');
  p('- **Needs**: the data sources the row depends on. If any of them is unconfigured or failed, the row is `null` (shown as a dash), never 0.');
  p('- Every rate is computed from **sums over the range**, never as an average of daily rates. Division by zero yields `null` (not computable), never 0.');
  p();

  for (const s of SECTIONS) {
    p(`## ${s.title}${s.ceoOnly ? ' (CEO only)' : ''}`);
    p();
    p(`Section id: \`${s.id}\`${s.ceoOnly ? ' — hidden unless the CEO section is unlocked (see docs/SETUP.md, "CEO lock").' : ''}`);
    p();
    if (s.subtitle) { p(s.subtitle); p(); }
    p(sectionTable(s));
    p();
  }

  p('## Cost categories');
  p();
  p('Rows in the Airtable *Dashboard Costs* table are mapped to CEO rows by their `Category` (matched case-insensitively). Any other category is counted as *uncategorised*: it still reduces profit and still counts in tracked costs, and the Data sources panel warns about it.');
  p();
  p('| Category (Airtable) | CEO row |\n|---|---|');
  for (const [cat, id] of Object.entries(COST_CATEGORIES)) p(`| ${cat} | \`${id}\` |`);
  p();
  p(`*Business costs* (subtracted for **Known profit after business costs**): total ad spend + ${BUSINESS_COST_ROWS.map(id => '`' + id + '`').join(' + ')} + uncategorised costs.`);
  p();
  p(`*Owner costs* (additionally subtracted for **Known profit after all costs**): ${OWNER_COST_ROWS.map(id => '`' + id + '`').join(' + ')}.`);
  p();
  p('**Monthly proration.** A cost row whose `Period` is *Monthly* is spread evenly over every day of the month its `Date` falls in (amount ÷ days in that month, per day inside the range). A *One-time* row lands entirely on its `Date`. So a $3,000 Monthly payroll row dated anywhere in September contributes $100 per September day: $100 to *Today*, $700 to a full week, $3,000 to the whole month.');
  p();

  p('## Campaign lines');
  p();
  p('Every ad campaign is classified onto exactly one line; the ad rows of a line feed the rows that name it. See docs/SETUP.md, "Campaign classification", for the rules and the `ADS_LINE_RULES` override.');
  p();
  p('| Line | Meaning |\n|---|---|');
  for (const [k, v] of Object.entries(LINE_LABEL)) p(`| \`${k}\` | ${v} |`);
  p();

  p('## Data sources');
  p();
  p('| Dataset key | Source |\n|---|---|');
  for (const [k, v] of Object.entries(DATASET_LABEL)) p(`| \`${k}\` | ${v} |`);
  p();

  p('## Ranges');
  p();
  p('Every metric is computed for the same set of ranges, all resolved against **today in the business timezone** (see "Timezone rule" below). Ranges are inclusive on both ends.');
  p();
  p('| Range id | Label | Definition |\n|---|---|---|');
  p(`| \`today\` | ${RANGE_LABEL.today} | the current calendar day |`);
  p(`| \`yesterday\` | ${RANGE_LABEL.yesterday} | the previous calendar day |`);
  p(`| \`l7d\` | ${RANGE_LABEL.l7d} | today and the 6 days before it (7 days) |`);
  p(`| \`l30d\` | ${RANGE_LABEL.l30d} | today and the 29 days before it (30 days) |`);
  p(`| \`mtd\` | ${RANGE_LABEL.mtd} | the 1st of the current month through today |`);
  p(`| \`lastMonth\` | ${RANGE_LABEL.lastMonth} | the whole previous calendar month |`);
  p();
  p('### Week 1–5 blocks');
  p();
  p('The month is cut into fixed 7-day blocks counted from the 1st, so a week never straddles two months and every month has the same block boundaries:');
  p();
  p('| Block | Days of the month |\n|---|---|\n| `w1` | 1st – 7th |\n| `w2` | 8th – 14th |\n| `w3` | 15th – 21st |\n| `w4` | 22nd – 28th |\n| `w5` | 29th – last day (1 to 3 days; absent only in a non-leap February) |');
  p();
  p('A block that starts after today is *future* and its values are `null`. The block containing today is *partial* (the payload flags it) and holds the days elapsed so far.');
  p();
  p('### Previous-period comparison');
  p();
  p('Each standard range carries a `prev` value for the equal-length period immediately before it, which the UI turns into the delta arrow:');
  p();
  p('- `today` compares to yesterday; `yesterday` to the day before it; `l7d` to the 7 days before those; `l30d` to the 30 days before those.');
  p('- `mtd` compares to **the same number of days of last month**, from its 1st: on the 12th, September 1–12 is compared to August 1–12. When last month is shorter than the elapsed day count (the 31st compared to a 30-day month), the comparison stops at last month\'s end.');
  p('- `lastMonth` compares to the whole month before it.');
  p();

  p('## Pace and status');
  p();
  p('A monthly target for a row is a record in the Airtable *Dashboard Targets* table keyed by the row id and the month (`YYYY-MM`). Status is judged on the **month-to-date** value only.');
  p();
  p('1. **Expected so far.** For a row that accumulates, `expected = target × (day of month ÷ days in month)`, today counting as a full day (on September 15, expected = target × 15 ÷ 30). For a non-accumulating row (a rate or an average), `expected = target`: the whole target applies from day one, because a 40% close rate should be 40% on the 3rd as much as on the 30th.');
  p('2. **Pace.** Phrased so that above 1 is always good:');
  p('   - higher-is-better rows: `pace = actual ÷ expected`');
  p('   - lower-is-better rows (costs, CPL, replacement rate, speed to lead): **inverted**, `pace = expected ÷ actual`. Spending $800 against an expected $1,000 is a pace of 1.25, ahead.');
  p('   - edge cases: when `expected` is 0, pace is 1 if `actual` is also 0, otherwise 0 for a lower-is-better row and ∞ for a higher-is-better row; a lower-is-better row with `actual` 0 has pace ∞.');
  p('   - context-only rows (`dir` = none) get no pace; their status is `partial` when a target is stored and `set_target` when it is not.');
  p('3. **Status** is the first band whose minimum the pace reaches:');
  p();
  p(statusTable());
  p();
  p('The API exposes `target`, `expected`, `pace` and `status` on every row; `format=flat` carries `target`, `pace` and `status`.');
  p();

  p('## Timezone rule');
  p();
  p(`- Every "today", "month to date" and "last 7 days" is resolved in **one business timezone**: \`DASHBOARD_TZ\` (an IANA zone; default \`${DEFAULT_TZ}\`), never the server's UTC clock. The payload's \`tz\` and \`today\` fields say which zone and which day were used.`);
  p('- **Airtable timestamps are converted.** A record\'s `createdTime`, a *Created At* value, an *Appointment Date* or *Submitted At* with a time, and a Whop `paid_at` are instants (UTC); each is converted to the business calendar day before it is counted. A lead created at 23:30 Toronto time on the 3rd is stored by Airtable as 03:30 UTC on the 4th and counts on the 3rd.');
  p('- **Date-only fields are used as-is.** A value like `2026-09-29` (the Closer EOD *Date*, a Dashboard Costs *Date*, a CRM *Date Added*) is already a calendar day and is never shifted.');
  p('- **Ad platform dates are used as reported.** Windsor.ai returns Facebook spend by the ad account\'s calendar day; the ad account\'s timezone should be set to the same zone as `DASHBOARD_TZ` so both agree.');
  p('- Connectors are asked for one extra day on each side of the window so a record that moves a day either way in conversion is never lost; the engine then slices exactly by range.');
  p();

  return out.join('\n') + '\n';
}

function main(argv = process.argv.slice(2)) {
  const doc = buildDoc();
  if (argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== doc) {
      process.stderr.write(`docs/METRICS.md is out of date. Run: npm run docs\n`);
      process.exit(1);
    }
    process.stdout.write('docs/METRICS.md is up to date.\n');
    return;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, doc);
  const rows = SECTIONS.reduce((n, s) => n + s.rows.length, 0);
  process.stdout.write(`Wrote ${OUT} (${SECTIONS.length} sections, ${rows} rows).\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
